import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { pinyin } from 'pinyin-pro'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const SRC = resolve(ROOT, 'server', 'data', 'exercises.json')
const NAMES_ZH = resolve(ROOT, 'server', 'data', 'exercise-names-zh.json')
const OUT = resolve(ROOT, 'server', 'seed.sql')

function sql(value) {
  if (value == null) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

/**
 * pinyin-pro defaults:
 * - no tone marks (toneType: 'none')
 * - ü rendered as 'v' via v: true (e.g. 女 -> nv)
 * - polyphonic characters use pinyin-pro's default preferred reading
 *   (卷 -> juan, 重 -> zhong, 行 -> xing). This is a known limitation —
 *   wrong readings for rare cases are acceptable for prefix/substring search.
 */
function pinyinFields(nameZh) {
  if (!nameZh) return { pinyin: null, initials: null }
  const full = pinyin(nameZh, { toneType: 'none', type: 'array', v: true })
    .join('')
    .toLowerCase()
  const initials = pinyin(nameZh, { pattern: 'first', toneType: 'none', type: 'array', v: true })
    .join('')
    .toLowerCase()
  return { pinyin: full || null, initials: initials || null }
}

const exercises = JSON.parse(await readFile(SRC, 'utf8'))

// Assign deterministic difficulty (1=easy, 2=medium, 3=hard) using exercise id hash.
function assignDifficulty(id) {
  const num = parseInt(id, 10) || 0
  const mod = num % 10
  if (mod <= 3) return 1
  if (mod <= 7) return 2
  return 3
}

// Curated Chinese names, keyed by exercise id. Missing ids stay NULL so the
// frontend falls back to English — the map can grow one entry at a time.
let namesZh = {}
try {
  const raw = JSON.parse(await readFile(NAMES_ZH, 'utf8'))
  for (const [id, name] of Object.entries(raw)) {
    if (id.startsWith('_')) continue
    if (typeof name === 'string' && name.trim()) namesZh[id] = name.trim()
  }
} catch {
  namesZh = {}
}

const rows = exercises.map((ex) => {
  const nameZh = namesZh[ex.id] ?? null
  const { pinyin: namePinyin, initials: nameInitials } = pinyinFields(nameZh)
  const difficulty = assignDifficulty(ex.id)
  return [
    ex.id,
    ex.name,
    nameZh,
    namePinyin,
    nameInitials,
    ex.category,
    ex.target,
    ex.equipment,
    ex.muscle_group,
    JSON.stringify(ex.secondary_muscles),
    ex.image,
    ex.gif_url,
    JSON.stringify(ex.instructions),
    JSON.stringify(ex.instruction_steps),
    difficulty,
  ]
})

const inserts = rows.map(
  (values) =>
    `INSERT INTO exercises (id, name, name_zh, name_pinyin, name_initials, category, target, equipment, muscle_group, secondary_muscles, image, gif_url, instructions, instruction_steps, difficulty) VALUES (${values
      .map(sql)
      .join(', ')});`,
)

const sqlText = `-- Generated by scripts/generate-seed.mjs — do not edit by hand.
-- Regenerate with: npm run db:gen
${inserts.join('\n')}
`

await mkdir(dirname(OUT), { recursive: true })
await writeFile(OUT, sqlText)
console.log(`Wrote ${OUT} with ${inserts.length} exercise inserts (${Object.keys(namesZh).length} with Chinese names).`)
